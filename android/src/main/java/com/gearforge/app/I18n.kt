    fun t(lang: Lang, key: String, vararg args: String): String {
        val template = (if (lang == Lang.EN) en else sv)[key] ?: en[key] ?: key
        if (args.isEmpty()) return template
        var result = template
        args.forEachIndexed { i, arg -> result = result.replace("{$i}", arg) }
        return result
    }

    /** Localized lookup with a caller-supplied fallback (used for data-driven core labels/help). */
    fun label(lang: Lang, key: String, fallback: String): String =
        (if (lang == Lang.EN) en else sv)[key] ?: fallback

    /** Localized help for a field key, falling back to the (English) core help text. */
    fun help(lang: Lang, fieldKey: String, fallback: String): String =
        (if (lang == Lang.EN) en else sv)["help_$fieldKey"] ?: fallback
